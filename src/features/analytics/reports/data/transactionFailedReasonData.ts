export function filterTransactionFailedReasons(
  rows: TransactionFailedReasonRow[],
  fromDate?: string,
  toDate?: string,
  errorDescription?: string,
): TransactionFailedReasonRow[] {
  return rows.filter((row) => {
    if (fromDate && row.transactionDate < fromDate) return false;
    if (toDate && row.transactionDate > toDate) return false;
    if (errorDescription) {
      const desc = errorDescription.toLowerCase();
      if (!row.errorDescription.toLowerCase().includes(desc)) return false;
    }
    return true;
  });
}
